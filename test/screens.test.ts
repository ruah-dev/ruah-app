function withJourney(product: ProductFile, screen: string): ProductFile {
  return {
    ...product,
    personas: [{ id: "retail", name: "Retail customer" }],
    journeys: [{ id: "pay-rent", name: "Pay rent", persona: "retail", goal: "Pay my rent", steps: [{ id: "s1", screen, action: "Opens it" }] }],
  };
}

describe("merge (§3.2)", () => {
  test("no file and no screens: nothing; first screens: a new file with empty personas / journeys", () => {
    expect(mergeScannedScreens(null, [])).toEqual({ product: null, warnings: [] });
    const { product, warnings } = mergeScannedScreens(null, [scan("home", "/home")]);
    expect(warnings).toEqual([]);
    expect(product).toEqual({ version: 1, personas: [], screens: [scan("home", "/home")], journeys: [] });
  });

  test("scan screens are replaced; user / agent screens and journeys are untouched", () => {
    const existing: ProductFile = withJourney(
      {
        ...emptyProduct(),
        screens: [
          { id: "checkout", name: "Checkout", route: "/checkout", source: "user" },
          { id: "idea", name: "Idea", source: "agent" },
          scan("home", "/home", { name: "Old name" }),
          scan("old", "/old"),
        ],
      },
      "checkout",
    );
    const { product, warnings } = mergeScannedScreens(existing, [scan("home", "/home"), scan("cards", "/cards")]);
    expect(warnings).toEqual([]);
    expect(product?.screens.map((s) => [s.id, s.source, s.name])).toEqual([
      ["checkout", "user", "Checkout"],
      ["idea", "agent", "Idea"],
      ["cards", "scan", "cards"],
      ["home", "scan", "home"],
    ]);
    expect(product?.journeys).toEqual(existing.journeys);
    expect(product?.personas).toEqual(existing.personas);
    expect(validateProduct(product).ok).toBe(true);
  });

  test("a referenced scanned screen that vanished stays, with a warning; unreferenced ones go", () => {
    const existing = withJourney({ ...emptyProduct(), screens: [scan("cards", "/cards"), scan("loans", "/loans"), scan("home", "/home")] }, "cards");
    const { product, warnings } = mergeScannedScreens(existing, [scan("home", "/home")]);
    expect(warnings).toEqual(["screen /cards no longer found in web"]);
    expect(product?.screens.map((s) => s.id)).toEqual(["cards", "home"]);
    expect(product?.screens[0]).toEqual(scan("cards", "/cards"));
    expect(validateProduct(product).ok).toBe(true);
  });

  test("a rescan keeps the id and shot of the screen at the same node + route; id clashes get a suffix", () => {
    const existing: ProductFile = withJourney(
      {
        ...emptyProduct(),
        screens: [
          { id: "home", name: "Home (hand-made)", source: "user" },
          scan("dashboard", "/", { shot: "dashboard.png" }),
        ],
      },
      "dashboard",
    );
    // The detector now calls "/" "home" (taken by the user's screen) and finds /home too.
    const { product, warnings } = mergeScannedScreens(existing, [scan("home", "/"), scan("home-2", "/home")]);
    expect(warnings).toEqual([]);
    expect(product?.screens.map((s) => [s.id, s.route, s.shot])).toEqual([
      ["home", undefined, undefined],
      ["dashboard", "/", "dashboard.png"],
      ["home-2", "/home", undefined],
    ]);
    // A user screen that claims a route replaces the scanned one.
    const claimed = mergeScannedScreens(
      { ...emptyProduct(), screens: [{ id: "my-cards", name: "Cards", route: "/cards", node: "web", source: "user" }] },
      [scan("cards", "/cards")],
    );
    expect(claimed.product?.screens.map((s) => s.id)).toEqual(["my-cards"]);
    expect(validateProduct(product).ok).toBe(true);
  });

  test("system namespacing: ids and nodes <repoId>:…, paths <repoId>/…", () => {
    expect(namespaceScreens("web", [scan("home", "/home")])).toEqual([
      { ...scan("home", "/home"), id: "web:home", node: "web:web", path: "web/web/src/routes/home.tsx" },
    ]);
  });
});

