const routes = (screens: Screen[]): string[] => screens.map((s) => s.route ?? "");
const byRoute = (screens: Screen[], route: string): Screen => {
  const s = screens.find((x) => x.route === route);
  if (s === undefined) throw new Error(`no screen for ${route}: ${routes(screens).join(", ")}`);
  return s;
};

